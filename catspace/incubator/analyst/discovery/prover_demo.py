def module(entry: dict) -> str:
    return TL.module_name(entry) + "_protection"


def lean_text(entry: dict, proof: "dict | None" = None) -> str:
    """The demonstration's Lean file (by code): it imports the entry's emitted module (the class, the moves) and states `protection` -- `sorry`, or the proof
    the tools found (written by code from an accepted run, never by hand)."""
    ns = TL.namespace(entry)
    gloss = ", ".join(TL.KIND[ch] for ch in entry["measure"]["class"].split("v")[0][1:]) or "none"
    body = TL.indent_proof(proof["proof"]) if proof else "  sorry"
    lemmas = (proof.get("lemmas") or "").rstrip() + "\n\n" if proof and proof.get("lemmas") else ""
    found = (f"/-! The proof below was FOUND by {proof['tool']} (prover.py, run {proof['run']}) and accepted by its check; written here by\n"
             f"prover_demo.lean_text, not by hand. -/\n\n") if proof else ""
    return (f"import Ideas.Mined.{TL.module_name(entry)}\n\n"
            f"/-! AUTO-GENERATED by catspace/incubator/analyst/discovery/prover_demo.py -- do not edit by hand. PLAN 73.6, THE DEMONSTRATION (Kaveh\n"
            f"2026-10-27): his PROTECTION LEMMA (\"you can prevent losing your rook no matter what he does because you have a king ... This should be a lemma in\n"
            f"itself\") over the class of the entry \"{entry['name']}\" (its units other than the king: {gloss}). The engine states it; the tools search for the\n"
            f"proof (prover.py). The form and why it is faithful: prover_demo.py's docstring. -/\n\n"
            f"set_option linter.unusedVariables false\n\nnamespace {ns}\n\nopen Chess hiding between\nopen Ideas.Vocabulary\n\n{found}{lemmas}"
            f"/-- THE PROTECTION LEMMA: in a position of the class, if a unit of ours other than the king is attacked by their side, we have a legal move after\n"
            f"which they are not stalemated and every unit of ours other than the king is not attacked by their side, or is defended by ours.\n"
            f"{'PROVED (the proof found by the tools, below).' if proof else 'OPEN: the tools task.'} -/\n"
            f"{STATEMENT.format(name=THEOREM if proof else 'conjecture_' + THEOREM)}\n{body}\n\nend {ns}\n")


# ---------------------------------------------------------------------------------------------------------------- the transcript

def _trim(text: str, n: int = 1800) -> str:
    text = (text or "").strip()
    return text if len(text) <= n else text[: n // 2] + "\n... [trimmed] ...\n" + text[-n // 2:]


def _block(text: str, lang: str = "") -> str:
    return f"```{lang}\n{text.rstrip()}\n```\n"


class Transcript:
    """demo.md, rewritten after every attempt (the harness's Log calls `row`)."""

    def __init__(self, entry: dict, run_info: dict, path: Path = TRANSCRIPT):
        self.entry, self.info, self.rows, self.tail, self.path = entry, run_info, [], "", path

    def row(self, r: dict) -> None:
        self.rows.append(r)
        self.write()

    def attempt(self, r: dict) -> str:
        tool = r.get("tool", "?")
        verdict = "ACCEPTED" if r.get("accepted") else "REJECTED"
        head = f"### {r['i']}. {r['t']} -- {tool}" + (f" `{r['tactic']}`" if r.get("tactic") else "") + f" on `{r.get('goal')}`"
        if r.get("depth"):
            head += f" (a sub-goal, depth {r['depth']})"
        out = [head + f" -- {verdict}" + (f" ({r.get('secs')} s of Lean)" if r.get("secs") is not None else "")]
        if r.get("tokens") is not None:
            out.append(f"The model wrote {r.get('tokens')} tokens in {r.get('gen_secs')} s (ended: {r.get('done_reason')}).")
            resp = r.get("response") or ""
            plan = resp.split("```")[0]
            out.append("Its plan (excerpt):\n\n" + "\n".join("> " + ln for ln in _trim(plan, 900).splitlines()) + "\n")
        if r.get("proof") is not None and r.get("tool") != "automation" and r.get("tool") != "copilot":
            if r.get("lemmas"):
                out.append("Its helper lemmas:\n\n" + _block(_trim(r["lemmas"], 1200), "lean"))
            out.append("Its proof (what Lean checked):\n\n" + _block(_trim(r["proof"], 1500), "lean"))
        if r.get("subgoals") is not None:
            out.append(f"Lean's extract_goal stated {r['subgoals']} sub-goal(s) from the sketch." if not r.get("errors") else "The sketch did not compile:")
        errs = r.get("errors") or []
        if errs:
            out.append("Lean said (first error, verbatim, trimmed):\n\n" + _block(_trim(re.sub(r"^\S*/scratch/|^error: ProverTools/", "", errs[0]), 1200)))
        elif r.get("why"):
            out.append("Verdict: " + "; ".join(r["why"]))
        return "\n".join(out) + "\n"

    def write(self) -> None:
        e, i = self.entry, self.info
        src = (TL.MINED_DIR / f"{module(e)}.lean").read_text()
        stmt = src[src.index("/-- THE PROTECTION LEMMA"):src.index(f"end {TL.namespace(e)}")].strip()
        parts = [f"# The prover, demonstrated: the protection lemma ({e['measure']['class']})\n",
                 f"Kaveh, 2026-10-27: \"you can prevent losing your rook no matter what he does because you have a king ... This should be a lemma in itself.\" "
                 f"The engine STATES it in Lean (`prover_demo.py`, by code); off-the-shelf tools SEARCH for the proof, cheapest first; Lean CHECKS every candidate "
                 f"in a scratch copy; nobody writes the proof. This page is rewritten after every attempt.\n",
                 f"Run `{i['run']}` -- started {i['started']}; tools {', '.join(i['tools'])}; the model {PR.MODEL} (reasoning mode {'on' if i['think'] else 'off'}, "
                 f"cap {PR.TOKEN_CAP} tokens a sample); the fuse {int(i['fuse'] // 60)} minutes; everything local (no network service).\n",
                 "## The statement\n", _block(stmt, "lean"), "### The form, and why it is faithful\n", "The NARROWEST FAITHFUL FORM: if a unit of ours other than the king is attacked by their side, we have a legal move "
                 "after which they are not stalemated and every unit of ours other than the king is not attacked by their side or is defended by ours. "
                 + FORM + "\n",
                 "## How a candidate is judged\n",
                 "Accepted only if the scratch copy compiles with no error and no `sorry`, `#print axioms` shows only propext / Classical.choice / Quot.sound, "
                 "and the text uses no native_decide, decide, fin_cases, interval_cases, Fintype / Finset.univ enumeration, sorry, admit or axiom.\n",
                 f"## The attempts ({len(self.rows)} so far)\n"] + [self.attempt(r) for r in self.rows] + [self.tail]
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text("\n".join(parts))


# ---------------------------------------------------------------------------------------------------------------- the run

def store(entry: dict, summary: dict, log=print) -> dict:
    """The outcome into the store: an ACCEPTED proof -> written into the file by code, built, checked again on the built module, the entry PROVED; else the
    entry CONJECTURE with the prover's last state. The sub-goals the tools proposed: the run's file and their entries (prover.sub_file_text / sub_entry)."""
    g = next(iter(summary["goals"].values()))                         # (the run's one top goal: protection, or conjecture_protection while open)
    ns, mod, day = TL.namespace(entry), module(entry), time.strftime("%Y-%m-%d")
    mreads = tuple(sorted(MN.measure_of(entry["measure"]["quantity"]).reads))
    path = TL.MINED_DIR / f"{mod}.lean"
    ok, why = False, ["no tool closed it within the fuse"]
    if g.get("closed_by"):
        path.write_text(lean_text(entry, dict(proof=g["proof"], lemmas=g.get("lemmas"), tool=g["closed_by"], run=summary["run"])))
        b = TL.build(mod)
        ok, why = (False, ["lake build: " + "; ".join(b["errors"][:3])]) if not b["ok"] or b["sorries"] else PR._axioms_of(
            mod, (f"{ns}.{THEOREM}",), (g["proof"], g.get("lemmas") or ""), "demo_record")
        if not ok:
            path.write_text(lean_text(entry))
    stmt = STATEMENT.format(name=THEOREM)
    e = dict(name=f"protection lemma {entry['measure']['class']}", kind=PR.role(stmt), reads=PR.reads_of(stmt, mreads), terms=[], origin="MINED", plan=["73.6"],
             journal=day, measure=None, implementation=[f"lean/ideas/Ideas/Mined/{mod}.lean:{THEOREM if ok else 'conjecture_' + THEOREM}"],
             status="PROVED" if ok else "CONJECTURE", lean=[f"{ns}.{THEOREM}"] if ok else [],
             evidence=dict(uses={}, confirmed=[f"PROVED by {g['closed_by']} (prover run {summary['run']}): accepted -- lake build, no sorry, the standard axioms "
                                               f"only, no enumeration"] if ok else [], refuted=[]),
             note=("Kaveh's protection lemma (2026-10-27), stated by the engine (prover_demo.py) over the class of " + entry["name"] + "; "
                   + (f"PROVED by {g['closed_by']}." if ok else f"not proved by the tools within the fuse (run {summary['run']}); the prover's last state: "
                      + str(g.get("last") or "?")[:400])))
    MN.write_entry(e)
    out = dict(entry=e, accepted=ok, why=why, sub_entries=[])
    sub = f"{mod}_{summary['mode']}"
    out["replaced"] = PR.drop_run_entries(sub)
    top_stmt = PR.goals_of(path)[0].stmt if PR.goals_of(path) else STATEMENT.format(name=THEOREM)
    proved, open_, out["not_words"] = PR.words_of(mod, ns, g, top_stmt, log)
    if proved or open_:
        (TL.MINED_DIR / f"{sub}.lean").write_text(PR.sub_file_text(mod, ns, summary["run"], summary["mode"], proved, open_))
        b = TL.build(sub)
        if b["ok"]:
            for n, v in proved.items():
                okn, whyn = PR._axioms_of(sub, (f"{ns}.{n}",), (v["proof"],), f"demo_record_{n}")
                se = PR.sub_entry(n, v, ns, sub, summary["run"], summary["mode"], e["name"], mreads, day, accepted=okn, why=whyn)
                MN.write_entry(se)
                out["sub_entries"].append(se)
            for n, v in open_.items():
                se = PR.sub_entry(n, v, ns, sub, summary["run"], summary["mode"], e["name"], mreads, day, accepted=None)
                MN.write_entry(se)
                out["sub_entries"].append(se)
        out["sub_build"] = b
    r = subprocess.run([str(Path(paths.REPO_ROOT) / ".venv" / "bin" / "python"), "-m", "catspace.incubator.analyst.lean_index", "build"], cwd=paths.REPO_ROOT,
                       capture_output=True, text=True, env=dict(os.environ, PYTHONPATH=str(paths.REPO_ROOT)))
    out["index"] = (r.stdout.strip().splitlines() or [""])[-1]
    out["validate"] = LS.validate(log=log, run=False)
    return out


def run(fuse: float = PR.FUSE_SECONDS, tools: tuple = ("automation", "copilot", "llm"), log=print) -> dict:
    """State the lemma, build it (one sorry), run the harness with the live transcript, write the outcome to the store, finish the transcript."""
    entry = LS.load(force=True)[ENTRY]
    mod = module(entry)
    (TL.MINED_DIR / f"{mod}.lean").write_text(lean_text(entry))
    b = TL.build(mod)
    log(f"OBS prover demo: stated Ideas.Mined.{mod}.conjecture_{THEOREM}; lake build ok {b['ok']}, sorry warnings {b['sorries']}, {b['secs']} s")
    if not b["ok"] or b["sorries"] != 1:
        raise SystemExit("the statement does not build with exactly one sorry: " + "; ".join(b["errors"][:4]))
    info = dict(run="(starting)", started=time.strftime("%Y-%m-%d %H:%M:%S"), tools=list(tools), think=False, fuse=fuse)
    T = Transcript(entry, info)
    T.write()

    def on_write(row):
        T.info["run"] = row.get("run", T.info["run"])
        T.row(row)
    summary = PR.prove(mod, "blind", tools, fuse, log_print=log, on_write=on_write, tag="demo")
    T.info["run"] = summary["run"]
    g = next(iter(summary["goals"].values()))
    subs = g.get("proposed") or []
    lines = ["## The sub-goals the model proposed\n"]
    if subs:
        lines.append("| sub-goal | of | statement (extract_goal) | fate |\n|---|---|---|---|")
        for sg in subs:
            fate = ("PROVED by " + g["proved"][sg["name"]]["tool"]) if sg["name"] in (g.get("proved") or {}) else \
                   ("OPEN: " + str((g.get("open") or {}).get(sg["name"], {}).get("last") or "not attacked")[:160])
            lines.append(f"| `{sg['name']}` | `{sg['parent']}` | `{' '.join(sg['statement'].split())[:300]}` | {fate} |")
    else:
        lines.append("None: no sketch of the model compiled into sub-goals within the fuse.")
    lines.append("\n## The outcome\n")
    if g.get("closed_by"):
        lines.append(f"CLOSED by {g['closed_by']} after {g['secs']} s. The accepted proof:\n\n" + _block(g["proof"], "lean"))
    else:
        lines.append(f"OPEN after the fuse ({g['secs']} s, {g['samples']} model samples). The goal stays as stated above with `sorry`. The last state:\n\n"
                     + _block(_trim(str(g.get("last") or "?"), 1500)))
    st = store(entry, summary, log)
    lines = finish_lines(g, st, lines)
    T.tail = "\n".join(lines) + "\n"
    T.write()
    log(f"OBS prover demo {mod}: {'CLOSED by ' + g['closed_by'] if g.get('closed_by') else 'OPEN after the fuse'}; samples {g['samples']}; sub-goals proposed "
        f"{len(subs)}, proved {len(g.get('proved') or {})}; not words {len(st['not_words'])}; the store entry {st['entry']['name']} {st['entry']['status']}; "
        f"transcript {T.path}")
    return dict(summary=summary, store=st)


def finish_lines(g: dict, st: dict, lines: list) -> list:
    """The transcript's last sections: which sub-goals are not words (and why), the store entry written."""
    if st.get("not_words"):
        lines.append("\n### Sub-goals not entered in the store (Lean decides: `prover.no_word`)\n")
        for n, why in st["not_words"].items():
            lines.append(f"- `{n}`: {why}.")
    lines.append("\n## The store entry written\n")
    lines.append(f"Accepted by the check on the built module: {st['accepted']} ({'; '.join(st['why']) if not st['accepted'] else 'no sorry, standard axioms, no enumeration'}). "
                 f"The index: {st['index']}. lemma_store validate: {'passes' if st['validate'] == 0 else 'FAILS'}.\n\n"
                 + _block(json.dumps(st["entry"], indent=1, ensure_ascii=False), "json"))
    for se in st["sub_entries"]:
        lines.append(f"Sub-goal entry `{se['name']}`: {se['status']}, kind {se['kind']}.")
    if st.get("replaced"):
        lines.append("Replaced (an earlier record of this run): " + ", ".join(f"`{n}`" for n in st["replaced"]) + ".")
    return lines


def rerecord(summary_path: str, log=print) -> dict:
    """Re-store a saved demonstration run (no proving) and rewrite the transcript's end from "## The sub-goals the model proposed"."""
    entry = LS.load(force=True)[ENTRY]
    summary = json.load(open(summary_path))
    g = next(iter(summary["goals"].values()))
    st = store(entry, summary, log)
    md = TRANSCRIPT.read_text()
    head = md[:md.index("## The store entry written")] if "## The store entry written" in md else md
    head = head[:head.index("### Sub-goals not entered")] if "### Sub-goals not entered" in head else head
    TRANSCRIPT.write_text(head.rstrip("\n") + "\n" + "\n".join(finish_lines(g, st, [])) + "\n")
    log(f"OBS prover demo re-recorded {summary['run']}: not words {len(st['not_words'])}, sub entries {len(st['sub_entries'])}, replaced {len(st['replaced'])}; "
        f"the store entry {st['entry']['name']} {st['entry']['status']}")
    return st


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--fuse", type=float, default=PR.FUSE_SECONDS)
    ap.add_argument("--tools", default="automation,copilot,llm")
    ap.add_argument("--record", default=None, help="re-store a saved run's summary.json (no proving) and rewrite the transcript's end")
    a = ap.parse_args(argv)
    if a.record:
        return rerecord(a.record)
    run(a.fuse, tuple(a.tools.split(",")))


if __name__ == "__main__":
    main()
