"""PLAN 73.6, THE DEMONSTRATION (Kaveh 2026-10-27, before the full K+R obligation): the whole loop end to end on ONE small lemma -- his protection lemma, "you
can prevent losing your rook no matter what he does because you have a king ... This should be a lemma in itself". The engine states it (this module, by
code, over the class the mined entry's emitted file defines); the harness (prover.py, cheapest first, every candidate checked by Lean) searches for the
proof; a human-readable TRANSCRIPT is rewritten after every attempt (artifacts/experiments/prover/demo.md, untracked); the outcome goes to the store.

THE STATEMENT, the narrowest faithful form chosen: in a position of the class (the side to move has its king and its other units, the other side a lone
king -- `inClass` of the emitted module), IF A UNIT OF OURS OTHER THAN THE KING IS ATTACKED BY THEIR SIDE, THEN WE HAVE A LEGAL MOVE after which they are not
stalemated and EVERY unit of ours other than the king is either not attacked by their side or attacked by ours (defended):

  theorem protection : ∀ p, inClass p → ∀ s pc, p.board s = some pc → pc.color = p.turn → pc.kind ≠ .king →
      isAttackedB p (Color.opposite p.turn) s = true →
      ∃ m, m ∈ legalMoves p ∧ ¬ stalemate (applyMove p m) ∧
        ∀ t qc, (applyMove p m).board t = some qc → qc.color = p.turn → qc.kind ≠ .king →
          isAttackedB (applyMove p m) (Color.opposite p.turn) t = false ∨ isAttackedB (applyMove p m) p.turn t = true

WHY FAITHFUL: "prevent losing your rook" is "after our move they cannot take it": a lone king takes a unit only when it attacks it and nothing of ours
defends it (taking a defended unit moves the king into check, which is not a legal move of the kernel) -- so "not attacked, or defended" is exactly "not
lost" here, read on the kernel's own attack relation (isAttackedB) rather than through the exchange law; "no matter what he does" is the universal over
every position of the class with the unit attacked (whatever their king did to attack it); "because you have a king" is the defence half of the disjunction
(the rook may also simply move away). The hypothesis (the unit is attacked) makes it the NARROWEST form: the threatened case is the lemma's content; the
quiet case asks only not to blunder. Not stalemating is required because a move that saves the rook by stalemating them saves nothing (the never-rule of the
technique, `ours`). Nothing names a unit kind: "a unit of ours other than the king" is the rook in K+R v K.

  python -m catspace.incubator.analyst.discovery.prover_demo [--fuse 5400] [--tools automation,copilot,llm]
"""
