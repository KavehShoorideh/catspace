"""plan 71.0 THE BOUNDARY MAP: per function of the discovery engine, the chess-bound calls it makes (`chess.*`, `board.*` methods of python-chess, `G.*` graph
words, `BD.*`/`PV.*` lemma families) -- what a Game / Words interface must take over, function by function. Writes docs/DOMAIN_MAP.md.

  .venv/bin/python scripts/domain_map.py
"""
from __future__ import annotations

import ast
import os
import re
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = ["agenda", "regress", "race", "plan67", "binder", "facts", "state", "graph_policy", "question_prior", "table", "analyse", "ponder"]
BOARD_METHODS = {"piece_at", "attackers", "attacks", "is_attacked_by", "legal_moves", "pseudo_legal_moves", "push", "pop", "san", "parse_san", "is_check", "is_checkmate",
                 "is_stalemate", "gives_check", "is_capture", "king", "pieces", "piece_map", "fen", "turn", "copy", "occupied_co", "piece_type_at", "is_legal", "is_pseudo_legal",
                 "epd", "pawns", "rooks", "queens", "knights", "bishops", "kings"}


def scan(path: str):
    src = open(path).read()
    tree = ast.parse(src)
    out = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            c = Counter()
            for sub in ast.walk(node):
                if isinstance(sub, ast.Attribute):
                    base = sub.value
                    if isinstance(base, ast.Name) and base.id == "chess":
                        c["chess." + sub.attr] += 1
                    elif isinstance(base, ast.Name) and base.id in ("G",):
                        c["G." + sub.attr] += 1
                    elif isinstance(base, ast.Name) and base.id in ("BD", "PV"):
                        c[base.id + "." + sub.attr] += 1
                    elif sub.attr in BOARD_METHODS:
                        c["board." + sub.attr] += 1
            if c:
                out[node.name] = c
    return out


def main():
    lines = ["# DOMAIN MAP (plan 71.0) -- generated by scripts/domain_map.py", "",
             "Per function: the chess-bound calls (python-chess `chess.*` and board methods, `G.*` graph words, `BD.*`/`PV.*` lemma families). A function with no row is generic as it stands.", ""]
    grand = Counter()
    for mod in MODULES:
        path = os.path.join(ROOT, "catspace", "incubator", "analyst", "discovery", mod + ".py")
        if not os.path.exists(path):
            continue
        found = scan(path)
        total = sum(sum(c.values()) for c in found.values())
        grand[mod] = total
        lines.append(f"## {mod}.py -- {len(found)} chess-bound functions, {total} calls")
        lines.append("")
        lines.append("| function | calls | the most frequent |")
        lines.append("|---|---|---|")
        for name, c in sorted(found.items(), key=lambda t: -sum(t[1].values()))[:40]:
            top = ", ".join(f"{k} {v}" for k, v in c.most_common(5))
            lines.append(f"| `{name}` | {sum(c.values())} | {top} |")
        lines.append("")
    lines.insert(4, "OBS domain map: " + ", ".join(f"{m} {n}" for m, n in grand.most_common()))
    lines.insert(5, "")
    open(os.path.join(ROOT, "docs", "DOMAIN_MAP.md"), "w").write("\n".join(lines) + "\n")
    print(lines[4])


if __name__ == "__main__":
    main()
