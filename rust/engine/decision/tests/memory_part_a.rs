//! (This file is in cs_decision's tests because it needs cs_gdl to compose a variant's text; cs_memory has no such dependency, and adding one changes Cargo.lock, which the kernels' certificates are keyed by.)
//! PLAN 79.19 PART A: THE STATEMENT AND ITS FOUR TESTS (SYSTEM_SPEC 11 "the layers": "a position is encoded and recreated"; "what the representation layer must be able to say"), on TWO games: the standard game (rules/chess.gdl) and one variant of the repo (rules/variants/kingofthehill.gdl).
//! (1) a position is encoded and recreated exactly over a large sample of positions of generated games (the game's own state, by replay and by its text; the facts through their canonical text);
//! (2) every statement of every standing and holder is written, read back and found identical (the patterns come from the games' own facts);
//! (3) a statement falls when, and only when, something it read changed (with a negative control that must be seen to fail);
//! (4) a pattern with placeholders binds on a position exactly where a slow plain reference says it does.
//! Plus: a statement written under one game is not seen by a reader of the other. The positions are generated by the game's fast kernel, which the description certifies by co-play (game/tests/facts.rs).
use cs_game::gdl_game::GdlGame;
use cs_game::kernel::{uci_to_spec_term, KernelGame};
use cs_game::rng::Rng;
use cs_game::{Fact, Game};
use cs_memory::lemma::{Arg, Lit};
use cs_memory::matcher::{bindings_fused, Binding, FactIndex};
use cs_memory::statement::{decode_facts, encode_facts, Change, Holder, Says, Standing, Statement};
use cs_memory::store::{GameKey, LongTerm};
use std::collections::BTreeSet;
use std::path::PathBuf;

fn rules(rel: &str) -> String { std::fs::read_to_string(PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../rules").join(rel)).unwrap() }

fn text_of(variant: &str) -> String {
    match variant { "chess" => rules("chess.gdl"), v => cs_gdl::compose(&rules("chess.gdl"), &rules(&format!("variants/{v}.gdl"))).unwrap() }
}

const GAMES: [&str; 2] = ["chess", "kingofthehill"];

/// each game gets its own random games
fn seed_of(v: &str) -> u64 { v.bytes().fold(0u64, |h, b| h.wrapping_mul(131).wrapping_add(b as u64)) }

/// One generated position: the moves from the start (as the kernel names them), its text, its key and its facts.
struct Pos { moves: Vec<String>, text: String, key: u64, facts: Vec<Fact> }

/// `games` random games of at most `plies` plies each, every position kept.
fn generated(variant: &str, games: usize, plies: usize, seed: u64) -> Vec<Vec<Pos>> {
    let k = KernelGame::new(variant, 518).unwrap();
    let mut rng = Rng::new(seed);
    let mut out = vec![];
    for _ in 0..games {
        let (mut s, mut moves, mut line) = (k.initial(), vec![], vec![]);
        for _ in 0..plies {
            line.push(Pos { moves: moves.clone(), text: k.fen(&s), key: k.key(&s), facts: k.base_facts(&s) });
            let legal = k.moves(&s);
            if legal.is_empty() || k.outcome(&s).is_some() { break; }
            let m = legal[rng.below(legal.len())].clone();
            moves.push(k.move_name(&s, &m));
            s = k.apply(&s, &m);
        }
        out.push(line);
    }
    out
}

// ------------------------------------------------------------------------------------------------------------------------------ (1) a position is encoded and recreated

#[test]
fn a_position_is_encoded_and_recreated_exactly() {
    for v in GAMES {
        let k = KernelGame::new(v, 518).unwrap();
        let g = GdlGame::load(v, &text_of(v)).unwrap();
        let sample = generated(v, 30, 40, 7919 + seed_of(v));
        let (mut n, mut by_replay, mut by_text, mut by_description, mut by_facts, mut dropped_ep) = (0, 0, 0, 0, 0, 0);
        for pos in sample.iter().flatten() {
            n += 1;
            // the game's own state by replaying its moves from the start
            let mut s = k.initial();
            for m in &pos.moves { s = k.apply(&s, &k.parse(&s, m).expect("a move of the record is legal")); }
            assert_eq!((k.key(&s), k.fen(&s)), (pos.key, pos.text.clone()));
            by_replay += 1;
            // by its text
            let k2 = KernelGame::from_fen(v, &pos.text).unwrap();
            assert_eq!(k2.key(&k2.initial()), pos.key, "{}", pos.text);
            // the text keeps the en passant square only where a capture is legal: the key and every other fact are exact, that one fact may be dropped (counted, printed)
            let (mut a, mut b) = (k2.base_facts(&k2.initial()), pos.facts.clone());
            if a != b { dropped_ep += 1; a.retain(|f| f.relation != "ep_square"); b.retain(|f| f.relation != "ep_square"); }
            assert_eq!(a, b, "{}", pos.text);
            by_text += 1;
            // the facts through their canonical text
            let mut want = pos.facts.clone();
            want.sort();
            want.dedup();
            assert_eq!(decode_facts(&encode_facts(&pos.facts)).unwrap(), want);
            by_facts += 1;
            // the description's state, reached by the same moves, holds the same facts (a sample of the positions: the evaluator is slow)
            if n % 12 == 0 {
                let mut t = g.initial();
                for m in &pos.moves { t = g.apply(&t, &g.find_move(&t, &uci_to_spec_term(m)).expect("the description has the move")); }
                let mut gf = g.base_facts(&t);
                gf.sort();
                assert_eq!(gf, want, "the description's facts at {}", pos.text);
                by_description += 1;
            }
        }
        println!("OBS 79.19 A1 {v}: positions {n}, recreated by replay {by_replay}, by text {by_text} (the text dropped the en passant square fact in {dropped_ep}: no capture was legal), facts through their text {by_facts}, the description's state compared on {by_description}");
        assert!(n >= 600);
    }
}

// ------------------------------------------------------------------------------------------------------------------------------ patterns from a game's facts

/// A pattern generalised from facts: each constant becomes a variable with probability one half, the same variable wherever the same constant occurs; the second literal joins on a shared constant where one exists; a third is negated and uses only variables or constants already bound.
fn pattern_from(facts: &[Fact], rng: &mut Rng) -> Vec<Lit> {
    if facts.is_empty() { return vec![]; }
    let mut var_of: Vec<(String, Option<String>)> = vec![];
    let mut lit_of = |f: &Fact, neg: bool, only_bound: bool, var_of: &mut Vec<(String, Option<String>)>, rng: &mut Rng| -> Lit {
        let args = f.args.iter().map(|a| {
            if let Some((_, v)) = var_of.iter().find(|(c, _)| c == a) { return match v { Some(v) => Arg::Var(v.clone()), None => Arg::Const(a.clone()) }; }
            if only_bound { return Arg::Const(a.clone()); }
            let v = if rng.below(2) == 0 { Some(format!("v{}", var_of.len())) } else { None };
            var_of.push((a.clone(), v.clone()));
            match v { Some(v) => Arg::Var(v), None => Arg::Const(a.clone()) }
        }).collect();
        Lit { neg, relation: f.relation.clone(), args }
    };
    let first = &facts[rng.below(facts.len())];
    let mut out = vec![lit_of(first, false, false, &mut var_of, rng)];
    if rng.below(3) > 0 {
        let joined: Vec<&Fact> = facts.iter().filter(|f| *f != first && f.args.iter().any(|a| first.args.contains(a))).collect();
        let second = if joined.is_empty() { &facts[rng.below(facts.len())] } else { joined[rng.below(joined.len())] };
        out.push(lit_of(second, false, false, &mut var_of, rng));
    }
    if rng.below(3) == 0 {
        let third = &facts[rng.below(facts.len())];
        let mut l = lit_of(third, true, true, &mut var_of, rng);
        // a negated literal whose variables are all bound is safe; a constant-only one is a plain absence
        l.args = l.args.into_iter().map(|a| match a { Arg::Var(v) if !out.iter().any(|p| !p.neg && p.vars().contains(&v)) => Arg::Const(v), x => x }).collect();
        out.push(l);
    }
    out
}

fn statement_of(id: String, pattern: Vec<Lit>) -> Statement { Statement { id, pattern, says: Says::Holds, standing: Standing::Fact, holder: Holder::Ours, also: vec![] } }

// ------------------------------------------------------------------------------------------------------------------------------ (2) every statement round-trips

#[test]
fn every_statement_of_every_standing_and_holder_is_written_and_read_back_identical() {
    let mut rng = Rng::new(79_19);
    let standings = [Standing::Fact, Standing::Proved("theorem_name".into()), Standing::Conjecture("games 1 to 40".into()), Standing::Belief { probability: 0.3333333333333333, count: 12 }];
    let mut n = 0;
    for v in GAMES {
        let sample = generated(v, 6, 30, 5 + seed_of(v));
        for pos in sample.iter().flatten().step_by(3) {
            let pat = pattern_from(&pos.facts, &mut rng);
            if pat.iter().all(|l| l.neg) { continue; }
            let sayings = [Says::Holds, Says::Number(rng.below(1000) as f64 / 7.0), Says::Lower { term: format!("[tuple t{}]", rng.below(9)), within: rng.below(5) as u32 }, Says::Proposes(cs_memory::lemma::Response { removed: vec![pat[0].clone()], added: vec![Lit::pos("moved", &["?m"])] })];
            for st in &standings { for h in [Holder::Ours, Holder::OursAboutOther] { for sa in &sayings {
                let s = Statement { id: format!("{v}-{n}"), pattern: pat.clone(), says: sa.clone(), standing: st.clone(), holder: h, also: vec![format!("key:{}", pos.key)] };
                if s.validate().is_err() { continue; }
                let text = s.to_json().to_string();
                assert_eq!(Statement::from_json(&serde_json::from_str(&text).unwrap()).unwrap(), s);
                n += 1;
            } } }
        }
    }
    println!("OBS 79.19 A2: {n} statements (every standing, both holders, every saying, patterns from the facts of {} games) written, read back and identical", GAMES.len());
    assert!(n > 1000);
}

// ------------------------------------------------------------------------------------------------------------------------------ (3) a statement falls when, and only when, something it read changed

/// The bindings of a pattern on a position's facts, as a set (no limit: a count that does not fit is a test fault).
fn bound(pat: &[Lit], facts: &[Fact]) -> BTreeSet<Binding> {
    let mut steps = 0;
    let (b, cut) = bindings_fused(pat, &Binding::new(), &FactIndex::new(facts), 1_000_000, &mut steps, u64::MAX);
    assert!(!cut);
    b.into_iter().collect()
}

#[test]
fn a_statement_falls_when_and_only_when_something_it_read_changed() {
    for v in GAMES {
        let mut rng = Rng::new(31_337);
        let sample = generated(v, 25, 40, 11 + seed_of(v));
        let (mut checked, mut fell, mut fell_same, mut stood, mut stood_changed, mut negative_control_broken, mut unread) = (0u64, 0u64, 0u64, 0u64, 0u64, 0u64, 0u64);
        for line in &sample {
            for w in line.windows(2) {
                let (before, after) = (&w[0], &w[1]);
                let ch = Change::between(&before.facts, &after.facts);
                let pool: Vec<Fact> = before.facts.iter().chain(after.facts.iter()).cloned().collect();
                for i in 0..20 {
                    let pat = pattern_from(&pool, &mut rng);
                    if pat.iter().all(|l| l.neg) { continue; }
                    let s = statement_of(format!("p{i}"), pat.clone());
                    let (b0, b1) = (bound(&pat, &before.facts), bound(&pat, &after.facts));
                    let falls = s.falls_by(&ch);
                    checked += 1;
                    // ONLY WHEN: a fall names a changed fact that unifies with a literal of the pattern
                    if falls { assert!(ch.added.iter().chain(ch.removed.iter()).any(|f| pat.iter().any(|l| cs_memory::statement::unifies(l, f)))); fell += 1; if b0 == b1 { fell_same += 1; } }
                    // WHEN: a statement that did not fall has the bindings it had
                    if !falls { assert_eq!(b0, b1, "{v}: a statement stood though its bindings changed: {pat:?} after {:?}", after.moves); stood += 1; }
                    if b0 != b1 { stood_changed += 1; assert!(falls); }
                    // the negative control: a reader that ignores the negated literals must be seen to fail on some pair
                    let positives: Vec<Lit> = pat.iter().filter(|l| !l.neg).cloned().collect();
                    let blind = statement_of("blind".into(), positives);
                    if !blind.falls_by(&ch) && b0 != b1 { negative_control_broken += 1; }
                    // a statement about a relation no fact has never falls
                    let ghost = statement_of("ghost".into(), vec![Lit::pos("no_such_relation", &["?x"])]);
                    if !ghost.falls_by(&ch) { unread += 1; } else { panic!("a statement of a relation nothing carries fell"); }
                }
            }
        }
        println!("OBS 79.19 A3 {v}: {checked} statement-changes checked; fell {fell} (of which {fell_same} bound the same before and after: the reading is conservative), stood {stood} with the same bindings every time; bindings changed in {stood_changed}, every one a fall; negative control (a reader blind to negated literals) wrongly stood {negative_control_broken} times; the unread relation stood {unread} times");
        assert!(checked > 5000 && fell > 100 && stood > 100);
        assert!(negative_control_broken > 0, "the control must fail somewhere, or the test could not tell");
    }
}

// ------------------------------------------------------------------------------------------------------------------------------ (4) a pattern binds exactly where a slow plain reference says

/// The plain reference: the literals in the order given, every row of every fact tried, no index, no reordering; then the negations as failures.
fn reference(pat: &[Lit], facts: &[Fact]) -> BTreeSet<Binding> {
    fn go(i: usize, pos: &[&Lit], neg: &[&Lit], b: Binding, facts: &[Fact], out: &mut BTreeSet<Binding>) {
        if i == pos.len() {
            let violated = neg.iter().any(|n| facts.iter().any(|f| f.relation == n.relation && f.args.len() == n.args.len() && n.args.iter().zip(&f.args).all(|(a, x)| match a { Arg::Const(c) => c == x, Arg::Var(v) => b.get(v).map_or(true, |bv| bv == x) })));
            if !violated { out.insert(b); }
            return;
        }
        for f in facts.iter().filter(|f| f.relation == pos[i].relation && f.args.len() == pos[i].args.len()) {
            let mut nb = b.clone();
            let mut ok = true;
            for (a, x) in pos[i].args.iter().zip(&f.args) {
                match a { Arg::Const(c) => if c != x { ok = false; break; }, Arg::Var(v) => match nb.get(v) { Some(bv) => if bv != x { ok = false; break; }, None => { nb.insert(v.clone(), x.clone()); } } }
            }
            if ok { go(i + 1, pos, neg, nb, facts, out); }
        }
    }
    let (pos, neg): (Vec<&Lit>, Vec<&Lit>) = (pat.iter().filter(|l| !l.neg).collect(), pat.iter().filter(|l| l.neg).collect());
    let mut out = BTreeSet::new();
    go(0, &pos, &neg, Binding::new(), facts, &mut out);
    out
}

#[test]
fn a_pattern_binds_exactly_where_a_slow_plain_reference_says() {
    for v in GAMES {
        let mut rng = Rng::new(4_242);
        let sample = generated(v, 25, 40, 23 + seed_of(v));
        let (mut checked, mut nonempty, mut joined, mut negated) = (0, 0, 0, 0);
        for pos in sample.iter().flatten().step_by(2) {
            for _ in 0..8 {
                let pat = pattern_from(&pos.facts, &mut rng);
                if pat.iter().all(|l| l.neg) { continue; }
                let (fast, slow) = (bound(&pat, &pos.facts), reference(&pat, &pos.facts));
                assert_eq!(fast, slow, "{v}: {pat:?} on {}", pos.text);
                checked += 1;
                nonempty += !slow.is_empty() as u32;
                joined += (pat.iter().filter(|l| !l.neg).count() > 1) as u32;
                negated += pat.iter().any(|l| l.neg) as u32;
            }
        }
        println!("OBS 79.19 A4 {v}: {checked} patterns on positions agree with the plain reference (bound somewhere {nonempty}, with a join {joined}, with a negation {negated})");
        assert!(checked > 1000 && nonempty > 100 && joined > 100 && negated > 50);
    }
}

// ------------------------------------------------------------------------------------------------------------------------------ one game's statement is not seen by a reader of the other

#[test]
fn a_statement_written_under_one_game_is_not_seen_by_a_reader_of_the_other() {
    let keys: Vec<GameKey> = GAMES.iter().map(|v| GameKey::of(v, &text_of(v))).collect();
    assert_ne!(keys[0], keys[1]);
    assert_ne!(keys[0].rules, keys[1].rules, "the content address of the rules tells the variants apart");
    let mut store = LongTerm::new();
    let s = statement_of("only-in-the-first".into(), vec![Lit::pos("cell", &["?f", "?r", "?c", "?k"])]);
    store.sleep().add(&keys[0], s.clone()).unwrap();
    let first = store.reader(&keys[0]).unwrap();
    assert_eq!(first.statement("only-in-the-first"), Some(&s));
    assert!(store.reader(&keys[1]).is_none(), "a game the store was told nothing of has no partition");
    store.sleep().add(&keys[1], statement_of("only-in-the-second".into(), vec![Lit::pos("cell", &["?f", "?r", "?c", "?k"])])).unwrap();
    let second = store.reader(&keys[1]).unwrap();
    assert!(second.statement("only-in-the-first").is_none() && first.statement("only-in-the-second").is_none());
    // the same name with other rules is another game
    let same_name_other_rules = GameKey::of(GAMES[0], &text_of(GAMES[1]));
    assert!(store.reader(&same_name_other_rules).is_none());
    println!("OBS 79.19 A5: a statement written under {} is read by its reader and not by the reader of {}; the same name with the other game's rules is a third, empty partition", GAMES[0], GAMES[1]);
}
